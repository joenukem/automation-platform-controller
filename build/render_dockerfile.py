#!/usr/bin/env python3
"""Render the upstream Dockerfile template headless, without ansible.

Upstream generates its Dockerfile via ansible-playbook; the only templating
actually used is jinja2 plus ansible's `bool` filter, so a 30-line renderer
replaces the whole toolchain (proven in Phase 0).
"""
import sys, os, jinja2

def main(awx_tree: str, receptor_image: str) -> None:
    tdir = os.path.join(awx_tree, 'tools/ansible/roles/dockerfile/templates')
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(tdir), keep_trailing_newline=True)
    env.filters['bool'] = lambda v: bool(v) if not isinstance(v, str) else v.lower() in ('1', 'true', 'yes', 'y')
    vars = dict(build_dev=False, kube_dev=False, headless=True,
                template_dest='_build', receptor_image=receptor_image)
    os.makedirs(os.path.join(awx_tree, '_build'), exist_ok=True)
    for t in ('supervisor_web.conf', 'supervisor_task.conf', 'supervisor_rsyslog.conf'):
        with open(os.path.join(awx_tree, '_build', t), 'w') as f:
            f.write(env.get_template(t + '.j2').render(**vars))
    df = env.get_template('Dockerfile.j2').render(**vars)
    # buildah here has no ssh forwarding; the git requirements are all https.
    df = df.replace('RUN --mount=type=ssh cd /tmp && make requirements_awx',
                    'RUN cd /tmp && make requirements_awx')
    # CTL-002: when a base-image mirror is configured, rewrite the quay.io
    # base + receptor FROMs to the franken registry so a release build has no
    # quay.io dependency for container images. (pip/dnf mirroring is separate.)
    mirror = os.environ.get('MIRROR_BASE')
    if mirror:
        df = df.replace('quay.io/centos/centos:stream9', mirror + '/centos/centos:stream9')
        df = df.replace('quay.io/ansible/receptor:devel', mirror + '/ansible/receptor:devel')
    # CTL-002 VENDORED mode: transform the Dockerfile so both stages install
    # offline from the captured bundle (VENDOR_IMAGE), for a deny-egress build.
    if os.environ.get('VENDORED'):
        vimg = os.environ.get('VENDOR_IMAGE', (mirror or 'quay.io') + '/automation-platform/vendor-capture:full')
        repo = ("RUN { echo '[vendored]'; echo 'name=vendored'; "
                "echo 'baseurl=file:///vendor/rpms'; echo 'enabled=1'; echo 'gpgcheck=0'; } "
                "> /etc/yum.repos.d/vendored.repo\n"
                "ENV PIP_NO_INDEX=1 PIP_FIND_LINKS=/vendor/wheels "
                "PIP_OPTIONS=\"--no-index --find-links /vendor/wheels --pre\"\n")
        # awx's Makefile requirements_awx has a supported airgap branch: when
        # $(PIP_OPTIONS) contains --no-index it installs requirements.txt +
        # requirements_local.txt (no --no-binary, no git clones). Generate the
        # local file from requirements_git.txt (name[extras], drop the @git URL).
        gitreq = os.path.join(awx_tree, 'requirements', 'requirements_git.txt')
        local = os.path.join(awx_tree, 'requirements', 'requirements_local.txt')
        # Bundle wheel/sdist filenames (from VENDOR_WHEEL_LIST) → name→version.
        # The git packages are dev-line pre-releases with local segments
        # (e.g. 0.0.1a6.dev599+gb52a9f809); pip will NOT select such a version
        # for a bare requirement even with --pre, so pin each one exactly.
        import re as _re2
        pins = {}
        for fn in os.environ.get('VENDOR_WHEEL_LIST', '').split():
            m = _re2.match(r'(?P<n>.+?)-(?P<v>\d[^-]*?)(?:-py3|-cp\d|)\.(?:whl|zip|tar\.gz)$', fn)
            if m:
                pins[_re2.sub(r'[-_.]+', '-', m.group('n')).lower()] = m.group('v')
        names = []
        for line in open(gitreq):
            line = line.strip()
            if not line or line.startswith('#') or '@' not in line:
                continue
            spec = line.split('@', 1)[0].strip()          # name[extras]
            base = spec.split('[', 1)[0]
            key = _re2.sub(r'[-_.]+', '-', base).lower()
            names.append(spec + ('==' + pins[key] if key in pins else ''))
        with open(local, 'w') as f:
            f.write('# generated by render_dockerfile VENDORED mode (CTL-002)\n')
            f.write('\n'.join(names) + '\n')
        # a) bundle stage before the first FROM
        df = ('FROM ' + vimg + ' AS vendor\n\n') + df
        # b) after each base FROM, mount the bundle + vendored repo + pip env
        import re as _re
        df = _re.sub(r'(FROM \S+/centos/centos:stream9[^\n]*\n)',
                     r'\1COPY --from=vendor /vendor /vendor\n' + repo, df)
        # c) drop dnf update + crb + config-manager fetch; force the vendored repo
        df = df.replace(
            "dnf -y update && dnf install -y 'dnf-command(config-manager)' && \\\n    dnf config-manager --set-enabled crb && \\\n    dnf -y install",
            "dnf install -y --disablerepo='*' --enablerepo=vendored")
        # d) epel/inotify/copr line -> plain vendored install
        df = df.replace(
            "RUN dnf install -y epel-next-release && dnf install -y inotify-tools && dnf remove -y epel-next-release",
            "RUN dnf install -y --disablerepo='*' --enablerepo=vendored inotify-tools")
        df = df.replace("RUN dnf install -y podman", "RUN dnf install -y --disablerepo='*' --enablerepo=vendored podman")
        # e) neutralise the copr rsyslog repo ADD (rsyslog is vendored)
        df = _re.sub(r'ADD https://copr\.fedorainfracloud\.org[^\n]*\n', '', df)
        # f) drop the ssh-keyscan of github (offline mode clones nothing)
        df = _re.sub(r'RUN ssh-keyscan github\.com[^\n]*\n', 'RUN mkdir -p ~/.ssh\n', df)
        # g1) the upstream Dockerfile ADDs only requirements.txt/_git/_tower —
        # the offline branch also needs requirements_local.txt in the build ctx.
        df = df.replace(
            "    requirements/requirements_git.txt \\\n    /tmp/requirements/",
            "    requirements/requirements_git.txt \\\n"
            "    requirements/requirements_local.txt \\\n    /tmp/requirements/")
        # g) the offline pip flags are BUILD-time only — neutralise them in the
        # shipped image so runtime pip (custom EE deps, admin installs) still
        # reaches an index. All pip-using RUN steps precede this override.
        # Non-empty false value: buildah/docker silently ignore `ENV KEY=`
        # (empty), so PIP_NO_INDEX=0 (pip reads it as false) is what sticks;
        # PIP_OPTIONS/PIP_FIND_LINKS are inert for runtime pip.
        df = df.rstrip('\n') + '\nENV PIP_NO_INDEX=0\n'
    with open(os.path.join(awx_tree, 'Dockerfile'), 'w') as f:
        f.write(df)
    print(f'rendered Dockerfile ({len(df)} bytes) + supervisor configs')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else (os.environ.get('MIRROR_BASE','').rstrip('/') + '/ansible/receptor:devel' if os.environ.get('MIRROR_BASE') else 'quay.io/ansible/receptor:devel'))
